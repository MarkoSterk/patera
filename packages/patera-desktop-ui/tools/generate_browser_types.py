class Normalize(ast.NodeTransformer):
    def visit_FunctionDef(self, node):
        self.generic_visit(node)
        if node.returns is None:
            node.returns = ast.Constant(None)
        node.args.defaults = [ast.Constant(Ellipsis) for _ in node.args.defaults]
        node.args.kw_defaults = [
            ast.Constant(Ellipsis) if x is not None else None
            for x in node.args.kw_defaults
        ]
        return node

    def visit_ClassDef(self, node):
        self.generic_visit(node)
        bases = {ast.unparse(b): b for b in node.bases}
        if "TypedDict" in bases and len(bases) > 1:
            del bases["TypedDict"]
        node.bases = list(bases.values())
        # Partial WebIDL interfaces can repeat methods non-contiguously.
        groups = {}
        for member in node.body:
            if isinstance(member, ast.FunctionDef):
                groups.setdefault(member.name, []).append(member)
        emitted = set()
        body = []
        for member in node.body:
            if not isinstance(member, ast.FunctionDef):
                body.append(member)
                continue
            if member.name in emitted:
                continue
            emitted.add(member.name)
            unique = {}
            for method in groups[member.name]:
                method.decorator_list = [
                    d for d in method.decorator_list if ast.unparse(d) != "overload"
                ]
                unique[ast.dump(method.args) + ast.dump(method.returns)] = method
            methods = list(unique.values())
            if len(methods) > 1:
                for method in methods:
                    method.decorator_list.insert(
                        0, ast.Name(id="overload", ctx=ast.Load())
                    )
            body.extend(methods)
        node.body = body
        return node


